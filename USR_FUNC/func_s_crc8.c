/********************CRC8校验程序********************/
//--输入：待校验的数据首字节地址,需要校验的数据字节长度
//--输出：8位CRC校验码
/************************/
//--使用方法：在数据发送阶段，用于生成需要发送的数据后面的8位校验码
//------------在数据接收阶段，将接收到的数据经过此运算看是否得到0，若为0则说明接收到的数据正确
/*****************************************************/
unsigned char FUNC_S_CRC8_CAL(unsigned char* pchMsg, unsigned int wDataLen)
{
	unsigned char crc8 = 0; // CRC字节初始化
	
	while (wDataLen--)
	{
		// 计算CRC
		crc8 = crc8_table[crc8 ^ *pchMsg++];
	}
	return crc8;
}

unsigned char FUNC_S_CRC8_CHECK(unsigned char* pchMsg, unsigned int wDataLen)
{
	unsigned char crc8 = 0; // CRC字节初始化
	
	while (wDataLen--)
	{
		// 计算CRC
		crc8 = crc8_table[crc8 ^ *pchMsg++];
	}
	return crc8;
}

